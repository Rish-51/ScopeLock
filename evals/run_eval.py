"""
Evaluation Engine for ScopeLock.
PLAN.md Section 9:
Runs the pipeline across synthetic sample briefs (1–5) and measures:
- Schema validity on first try rate
- Retries per run
- Grounded quote ratio
- Latency (total and per stage)
- Tokens in / out
- Cold-start load_ms
- Milestone hour totals
Outputs structured report to evals/results.md.
"""

import sys
import time
import json
import asyncio
from pathlib import Path
from typing import Dict, List, Any

ROOT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT_DIR))

from backend.core.parser import parse_document
from backend.services.scoping_service import ScopingService
from backend.core.ollama_client import OllamaClient
from backend.core.tracing import trace_session, get_current_trace

BRIEFS_DIR = ROOT_DIR / "backend" / "tests" / "sample_briefs"
RESULTS_FILE = ROOT_DIR / "evals" / "results.md"


async def evaluate_brief(brief_path: Path, model: str) -> Dict[str, Any]:
    print(f"[*] Evaluating '{brief_path.name}' on model '{model}'...")
    raw_bytes = brief_path.read_bytes()
    doc = parse_document(raw_bytes, brief_path.name)

    client = OllamaClient(default_model=model)
    service = ScopingService(ollama_client=client)

    start_time = time.time()
    with trace_session():
        proposal = await service.analyze_document(doc=doc)
        traces = get_current_trace()
    elapsed_total_s = round(time.time() - start_time, 2)

    # Calculate metrics
    chat_spans = [s for s in traces if s["op"] == "gen_ai.chat"]
    total_tokens_in = sum(s["attributes"].get("gen_ai.usage.input_tokens", 0) for s in chat_spans)
    total_tokens_out = sum(s["attributes"].get("gen_ai.usage.output_tokens", 0) for s in chat_spans)
    total_tokens = total_tokens_in + total_tokens_out

    cold_start_load_ms = chat_spans[0]["attributes"].get("scopelock.load_ms", 0.0) if chat_spans else 0.0

    retries_count = sum(1 for s in chat_spans if s["attributes"].get("scopelock.attempt", 1) > 1)

    grounding = proposal.grounding
    grounded_ratio = (
        round((grounding.grounded_quotes / max(1, grounding.total_quotes)) * 100, 1)
        if grounding.total_quotes > 0
        else 100.0
    )

    base_hours = sum(m.hours_min for m in proposal.plan.milestones)
    base_hours_max = sum(m.hours_max for m in proposal.plan.milestones)

    return {
        "brief": brief_path.name,
        "model": model,
        "char_count": doc.char_count,
        "est_tokens": doc.estimated_tokens,
        "is_chunked": doc.is_chunked,
        "elapsed_s": elapsed_total_s,
        "tokens_in": total_tokens_in,
        "tokens_out": total_tokens_out,
        "total_tokens": total_tokens,
        "cold_start_load_ms": cold_start_load_ms,
        "retries": retries_count,
        "first_try_valid": retries_count == 0,
        "req_count": len(proposal.requirements.requirements),
        "risks_count": len(proposal.risks.risks),
        "scope_guard_count": len(proposal.risks.scope_creep_warnings),
        "milestones_count": len(proposal.plan.milestones),
        "hours_range": f"{base_hours}-{base_hours_max}",
        "adjusted_hours": f"{proposal.commercial.hours_min_adjusted:.1f}-{proposal.commercial.hours_max_adjusted:.1f}",
        "fixed_price": f"{proposal.commercial.currency} {proposal.commercial.recommended_fixed_price:,.2f}",
        "grounded_ratio": f"{grounded_ratio}% ({grounding.grounded_quotes}/{grounding.total_quotes})",
    }


def write_results_markdown(results: List[Dict[str, Any]]):
    lines = []
    lines.append("# ScopeLock Benchmark & Evaluation Results")
    lines.append("\n*Generated by `evals/run_eval.py` across synthetic test briefs.*")
    lines.append("\n## Summary Table\n")
    lines.append(
        "| Brief | Model | Req Count | Grounded Ratio | Tokens (In/Out) | Latency | Retries | Fixed Price |"
    )
    lines.append(
        "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
    )

    for r in results:
        lines.append(
            f"| `{r['brief']}` | `{r['model']}` | {r['req_count']} | {r['grounded_ratio']} | {r['tokens_in']}/{r['tokens_out']} | {r['elapsed_s']}s | {r['retries']} | {r['fixed_price']} |"
        )

    lines.append("\n## Detailed Metrics per Brief\n")
    for r in results:
        lines.append(f"### {r['brief']} ({r['model']})")
        lines.append(f"- **Document Size:** {r['char_count']} chars (~{r['est_tokens']} estimated tokens, chunked: {r['is_chunked']})")
        lines.append(f"- **Total Latency:** {r['elapsed_s']} seconds (cold-start load: {r['cold_start_load_ms']} ms)")
        lines.append(f"- **Tokens:** {r['total_tokens']} total ({r['tokens_in']} prompt eval + {r['tokens_out']} eval)")
        lines.append(f"- **Schema First-Try Valid:** {r['first_try_valid']} (repair retries: {r['retries']})")
        lines.append(f"- **Requirements Extracted:** {r['req_count']}")
        lines.append(f"- **Quote Grounding:** {r['grounded_ratio']}")
        lines.append(f"- **Technical Risks:** {r['risks_count']} identified")
        lines.append(f"- **Scope-Creep Guardrails:** {r['scope_guard_count']} ambiguous phrases flagged with SOW clauses")
        lines.append(f"- **Engineering Effort:** {r['hours_range']} base hrs -> {r['adjusted_hours']} adjusted hrs")
        lines.append(f"- **Recommended Commercial Price:** {r['fixed_price']}")
        lines.append("")

    RESULTS_FILE.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_FILE.write_text("\n".join(lines), encoding="utf-8")
    print(f"\n[+] Wrote benchmark evaluation report to '{RESULTS_FILE}'")


async def main():
    brief_files = sorted(BRIEFS_DIR.glob("*.md"))
    if not brief_files:
        print("No sample briefs found.")
        return

    model = "gemma4:e4b"
    results = []
    for bf in brief_files:
        try:
            res = await evaluate_brief(bf, model)
            results.append(res)
        except Exception as e:
            print(f"[!] Error evaluating {bf.name}: {e}")

    if results:
        write_results_markdown(results)


if __name__ == "__main__":
    asyncio.run(main())
